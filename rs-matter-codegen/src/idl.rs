/// A trait implemented by all structure-like entities in the IDL, i.e. `Struct` and `Event`.
pub(crate) trait StructLike {
    fn id(&self) -> &str;

    fn fields(&self) -> &[StructField];
}

impl<T> StructLike for &T
where
    T: StructLike,
{
    fn id(&self) -> &str {
        (*self).id()
    }

    fn fields(&self) -> &[StructField] {
        (*self).fields()
    }
}

impl StructLike for Struct {
    fn id(&self) -> &str {
        &self.id
    }

    fn fields(&self) -> &[StructField] {
        &self.fields
    }
}

impl StructLike for Event {
    fn id(&self) -> &str {
        &self.id
    }

    fn fields(&self) -> &[StructField] {
        &self.fields
    }
}

/// Some context data for IDL generation
///
/// Data that is necessary to be able to code generate various bits.
/// In particular, matter_rs types (e.g. TLV or traits) are needed,
/// hence the crate name is provided
pub struct IdlGenerateContext {
    rs_matter_crate: Ident,
}

impl IdlGenerateContext {
    pub fn new(rs_matter_crate: impl AsRef<str>) -> Self {
        Self {
            rs_matter_crate: Ident::new(rs_matter_crate.as_ref(), Span::call_site()),
        }
    }
}

/// Return a token stream containing Rust types corresponding to all definitions
/// in the provided IDL cluster:
///
#[allow(unused)]
pub fn cluster(cluster: &Cluster, globals: &Entities, context: &IdlGenerateContext) -> TokenStream {
    cluster_internal(cluster, globals, true, context)
}

/// Return the module name and inner content for a cluster, without the outer `pub mod` wrapper.
/// Useful for generating per-cluster files.
pub fn cluster_content(
    cluster: &Cluster,
    globals: &Entities,
    context: &IdlGenerateContext,
) -> (String, TokenStream) {
    let module_name = id::idl_field_name_to_rs_name(&cluster.id);
    let content = cluster_content_internal(cluster, globals, true, context);
    (module_name, content)
}

fn cluster_content_internal(
    cluster: &Cluster,
    globals: &Entities,
    with_async: bool,
    context: &IdlGenerateContext,
) -> TokenStream {
    let entities = &EntityContext::new(Some(cluster), globals);
    let bitmaps = bitmap::bitmaps(&cluster.entities.bitmaps, context);
    let enums = enumeration::enums(&cluster.entities.enums, context);
    let struct_tags = struct_in::struct_tags(&cluster.entities.structs, context);
    let structs = struct_in::structs(&cluster.entities.structs, entities, context);
    let struct_builders = struct_out::struct_builders(&cluster.entities.structs, entities, context);
    let event_tags = struct_in::struct_tags(&cluster.events, context);
    let events = struct_in::structs(&cluster.events, entities, context);
    let event_builders = struct_out::struct_builders(&cluster.events, entities, context);
    let events_cont = event::events(&cluster.events, entities, context);

    let attribute_id = cluster::attribute_id(cluster, context);
    let command_id = cluster::command_id(cluster, context);
    let command_response_id = cluster::command_response_id(entities, context);
    let event_id = cluster::event_id(cluster, context);
    let cluster_meta = cluster::cluster(cluster, globals, context);

    let handler = handler::handler(false, false, cluster, globals, context);
    let handler_inherent_impl = handler::handler(false, true, cluster, globals, context);
    let handler_adaptor = handler::handler_adaptor(false, cluster, globals, context);

    let client_im_glue = client::client_im(cluster, entities, context);

    let quote = quote!(
        #bitmaps

        #enums

        #struct_tags

        #structs

        #struct_builders

        #event_tags

        #events

        #event_builders

        #events_cont

        #attribute_id

        #command_id

        #command_response_id

        #event_id

        #cluster_meta

        #handler

        #handler_inherent_impl

        #handler_adaptor

        #client_im_glue
    );

    if with_async {
        let async_handler = handler::handler(true, false, cluster, globals, context);
        let async_handler_inherent_impl = handler::handler(true, true, cluster, globals, context);
        let async_handler_adaptor = handler::handler_adaptor(true, cluster, globals, context);

        quote!(
            #quote

            #async_handler

            #async_handler_inherent_impl

            #async_handler_adaptor
        )
    } else {
        quote
    }
}

#[allow(unused)]
fn cluster_internal(
    cluster: &Cluster,
    globals: &Entities,
    with_async: bool,
    context: &IdlGenerateContext,
) -> TokenStream {
    let cluster_module_name = Ident::new(
        &id::idl_field_name_to_rs_name(&cluster.id),
        Span::call_site(),
    );

    let cluster_module_doc = Literal::string(&format!(
        "This module contains generated Rust types for the \"{}\" cluster",
        cluster.id
    ));

    let quote = cluster_content_internal(cluster, globals, with_async, context);

    quote!(
        #[doc = #cluster_module_doc]
        #[allow(async_fn_in_trait)]
        #[allow(unknown_lints)]
        #[allow(clippy::uninlined_format_args)]
        #[allow(unexpected_cfgs)]
        pub mod #cluster_module_name {
            #quote
        }
    )
}

/// Return a token stream containing Rust types corresponding to all global definitions
///
pub fn globals(globals: &Entities, context: &IdlGenerateContext) -> TokenStream {
    globals_internal(globals, context)
}

fn globals_internal(globals: &Entities, context: &IdlGenerateContext) -> TokenStream {
    let module_name = Ident::new("globals", Span::call_site());

    let module_doc = Literal::string("This module contains generated global Rust types");

    let entities = &EntityContext::new(None, globals);
    let bitmaps = bitmap::bitmaps(&globals.bitmaps, context);
    let enums = enumeration::enums(&globals.enums, context);
    let struct_tags = struct_in::struct_tags(&globals.structs, context);
    let structs = struct_in::structs(&globals.structs, entities, context);
    let struct_builders = struct_out::struct_builders(&globals.structs, entities, context);

    let quote = quote!(
        #bitmaps

        #enums

        #struct_tags

        #structs

        #struct_builders
    );

    quote!(
        #[doc = #module_doc]
        #[allow(unknown_lints)]
        #[allow(clippy::uninlined_format_args)]
        #[allow(unexpected_cfgs)]
        pub mod #module_name {
            #quote
        }
    )
}

