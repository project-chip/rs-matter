//! Native Rust implementation of the Matter protocol by CSA-IOT.
//!
//! This crate implements the Matter specification that can be run on embedded devices
//! to build Matter-compatible smart-home/IoT devices.
//!
//! Look at the examples project in the workspace for example applications built using this crate, and the tests directory for unit tests.
//!
//! Start off exploring by going to the [Matter] object.
//!
//! The implementation is split into the `rs-matter-*` crates. This crate puts
//! them together under one set of paths and features.
#![cfg_attr(not(feature = "std"), no_std)]
#![allow(async_fn_in_trait)]
#![allow(unknown_lints)]
#![allow(clippy::uninlined_format_args)]
#![recursion_limit = "1024"]
// `cargo llvm-cov` sets `coverage_nightly` when it runs on a nightly toolchain;
// the test modules are then excluded from the coverage report
#![cfg_attr(all(coverage_nightly, test), feature(coverage_attribute))]

#[cfg(feature = "alloc")]
extern crate alloc;

pub mod dm;

// The state of the node: the fabrics, the fail-safe etc.
pub use rs_matter_node_core::*;

// `Matter` and the transport
#[cfg(feature = "groups")]
pub use rs_matter_node::groupcast;
#[cfg(feature = "pics")]
pub use rs_matter_node::pics;
pub use rs_matter_node::transport;
pub use rs_matter_node::{acl, BootReason, Matter, MatterState, Transaction};

pub use rs_matter_bdx as bdx;
pub use rs_matter_im as im;
pub use rs_matter_onboard as onboard;
pub use rs_matter_respond as respond;
pub use rs_matter_sc as sc;

pub use rs_matter_dm::{clusters, ota, root_endpoint};

pub use rs_matter_cert as cert;
pub use rs_matter_cert::attest;
pub use rs_matter_crypto as crypto;
pub use rs_matter_crypto::group_keys;
pub use rs_matter_pairing as pairing;
pub use rs_matter_utils as utils;
pub use rs_matter_utils::error;

pub use rs_matter_dm_core::persist;
pub use rs_matter_dm_core::{
    attribute_enum, attributes, command_enum, commands, devices, event_enum, events, except,
    handler_chain_type, with,
};
pub use rs_matter_tlv as tlv;
pub use rs_matter_tlv::bitflags_tlv;

/// Re-export several crates
///
/// This is necessary for crates used in the code generated by the proc-macros
pub mod reexport {
    pub use bitflags;
    #[cfg(feature = "defmt")]
    pub use defmt;
    pub use strum;
}
